"""
AEGIS GitHub MCP Server
Integrates real GitHub REST API v3 pull request dispatch and automated remediation workflow.
Exposes typed PR creation tools with repository validation, branch management, patch application,
commit creation, and pull request generation with detailed CVE and remediation metadata.
Follows least-privilege security and fails cleanly without fabricating links or success.
"""

import os
import re
import base64
import logging
from typing import Any, Dict, Optional
import httpx
from mcp.server.mcpserver import MCPServer
from app.core.config import settings

logger = logging.getLogger(__name__)

github_mcp = MCPServer("aegis-github-server")

def _get_github_token() -> Optional[str]:
    """Retrieve GitHub token strictly from environment or configuration."""
    return settings.GITHUB_TOKEN or os.getenv("GITHUB_TOKEN")

def _validate_repo_name(repo_name: str) -> Optional[tuple[str, str]]:
    """
    Validate repository format (owner/repo).
    Returns (owner, repo) tuple if valid, None otherwise.
    """
    if not repo_name or not isinstance(repo_name, str):
        return None
    repo_name = repo_name.strip()
    match = re.match(r"^([a-zA-Z0-9_.-]+)/([a-zA-Z0-9_.-]+)$", repo_name)
    if match:
        return match.group(1), match.group(2)
    return None

def _sanitize_branch_name(name: str) -> str:
    """Sanitize candidate string into a safe Git branch name."""
    clean = re.sub(r"[^a-zA-Z0-9._-]", "-", name)
    clean = re.sub(r"-+", "-", clean).strip("-.")
    return clean[:80] or "patch"

@github_mcp.tool()
async def create_pull_request(
    repo_name: str,
    finding_title: str,
    remediation_patch: str,
    cve_id: Optional[str] = None,
    branch_name: Optional[str] = None,
    target_branch: str = "main",
    patch_file_path: Optional[str] = None,
    vulnerability_details: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Creates a remediation Pull Request on GitHub containing an automated security patch.
    1. Validates repository identifier format (owner/repo).
    2. Validates GitHub token availability and permissions.
    3. Checks target repository and retrieves the base branch commit SHA.
    4. Prevents duplicate PRs by checking existing open pull requests.
    5. Creates a dedicated remediation branch.
    6. Commits the approved remediation patch.
    7. Opens a Pull Request with complete vulnerability details and remediation metadata.
    """
    token = _get_github_token()
    if not token or not token.strip():
        logger.warning("GitHub PR dispatch requested but GITHUB_TOKEN is not configured.")
        return {
            "status": "UNAVAILABLE",
            "repo_name": repo_name,
            "target_branch": target_branch,
            "error": "GitHub pull request dispatch is not configured; no branch, commit, or pull request was created (GITHUB_TOKEN environment variable is missing or empty)."
        }

    if not remediation_patch or not remediation_patch.strip():
        return {
            "status": "ERROR",
            "repo_name": repo_name,
            "error": "Cannot create Pull Request without valid remediation patch content."
        }

    repo_parts = _validate_repo_name(repo_name)
    if not repo_parts:
        return {
            "status": "ERROR",
            "repo_name": repo_name,
            "error": f"Invalid repository format '{repo_name}'. Expected format: 'owner/repository'."
        }

    owner, repo = repo_parts
    base_api_url = settings.GITHUB_API_URL.rstrip("/")
    headers = {
        "Authorization": f"Bearer {token.strip()}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "AEGIS-CTEM-Security-Platform",
    }

    cve_label = f"[{cve_id}] " if cve_id else ""
    pr_title = f"fix(security): {cve_label}{finding_title.strip()}"[:120]
    safe_title_slug = _sanitize_branch_name(cve_id or finding_title)
    feature_branch = branch_name or f"aegis/remediation-{safe_title_slug}"
    target_file = patch_file_path or "SECURITY_REMEDIATION.diff"

    pr_body = (
        f"## 🛡️ AEGIS AI Automated Security Remediation\n\n"
        f"**Vulnerability:** {finding_title}\n"
    )
    if cve_id:
        pr_body += f"**CVE Reference:** `{cve_id}`\n"
    pr_body += (
        f"**Target Branch:** `{target_branch}`\n"
        f"**Remediation Branch:** `{feature_branch}`\n\n"
        f"### Summary of Security Patch\n"
        f"This remediation patch was generated by the AEGIS Multi-Agent CTEM Pipeline and explicitly approved by an authorized security analyst.\n\n"
        f"```diff\n{remediation_patch.strip()}\n```\n\n"
        f"---\n"
        f"*Automated security patch generated by AEGIS CTEM. Auto-merge is strictly disabled.*"
    )

    timeout = httpx.Timeout(15.0, connect=10.0)
    async with httpx.AsyncClient(headers=headers, timeout=timeout) as client:
        # Step 1: Verify repository access and retrieve default/target branch ref
        repo_resp = await client.get(f"{base_api_url}/repos/{owner}/{repo}")
        if repo_resp.status_code == 401:
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": "GitHub API authentication failed. The provided GITHUB_TOKEN is invalid or expired."
            }
        if repo_resp.status_code in (403, 404):
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"Repository '{repo_name}' was not found or the token lacks necessary permissions (HTTP {repo_resp.status_code})."
            }
        if repo_resp.status_code != 200:
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"GitHub API returned unexpected status {repo_resp.status_code} while fetching repository."
            }

        # Step 2: Check for existing open duplicate PRs
        prs_resp = await client.get(
            f"{base_api_url}/repos/{owner}/{repo}/pulls",
            params={"state": "open", "head": f"{owner}:{feature_branch}"}
        )
        if prs_resp.status_code == 200:
            existing_prs = prs_resp.json()
            if existing_prs and len(existing_prs) > 0:
                existing_pr = existing_prs[0]
                return {
                    "status": "DUPLICATE",
                    "repo_name": repo_name,
                    "pr_url": existing_pr.get("html_url"),
                    "pr_number": existing_pr.get("number"),
                    "branch_name": feature_branch,
                    "error": f"A pull request from branch '{feature_branch}' already exists: {existing_pr.get('html_url')}"
                }

        # Step 3: Get SHA of target branch
        ref_resp = await client.get(f"{base_api_url}/repos/{owner}/{repo}/git/ref/heads/{target_branch}")
        if ref_resp.status_code != 200:
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"Target branch '{target_branch}' not found in repository '{repo_name}'."
            }
        base_sha = ref_resp.json()["object"]["sha"]

        # Step 4: Create new branch ref (or update if already exists)
        create_ref_resp = await client.post(
            f"{base_api_url}/repos/{owner}/{repo}/git/refs",
            json={"ref": f"refs/heads/{feature_branch}", "sha": base_sha}
        )
        if create_ref_resp.status_code == 422:
            # Branch already exists; check if we should update or proceed
            branch_ref_resp = await client.get(f"{base_api_url}/repos/{owner}/{repo}/git/ref/heads/{feature_branch}")
            if branch_ref_resp.status_code != 200:
                return {
                    "status": "ERROR",
                    "repo_name": repo_name,
                    "error": f"Failed to initialize branch '{feature_branch}' (HTTP 422)."
                }
        elif create_ref_resp.status_code not in (200, 201):
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"Failed to create branch '{feature_branch}': {create_ref_resp.text}"
            }

        # Step 5: Check if patch file exists on branch to provide sha for update
        existing_file_resp = await client.get(
            f"{base_api_url}/repos/{owner}/{repo}/contents/{target_file}",
            params={"ref": feature_branch}
        )
        file_sha = None
        if existing_file_resp.status_code == 200:
            file_sha = existing_file_resp.json().get("sha")

        # Step 6: Commit patch content to the branch
        content_b64 = base64.b64encode(remediation_patch.encode("utf-8")).decode("utf-8")
        commit_payload: Dict[str, Any] = {
            "message": f"fix(security): apply remediation patch for {cve_id or finding_title}",
            "content": content_b64,
            "branch": feature_branch,
        }
        if file_sha:
            commit_payload["sha"] = file_sha

        put_resp = await client.put(
            f"{base_api_url}/repos/{owner}/{repo}/contents/{target_file}",
            json=commit_payload
        )
        if put_resp.status_code not in (200, 201):
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"Failed to commit remediation patch to branch '{feature_branch}': {put_resp.text}"
            }

        # Step 7: Create Pull Request
        pr_create_resp = await client.post(
            f"{base_api_url}/repos/{owner}/{repo}/pulls",
            json={
                "title": pr_title,
                "body": pr_body,
                "head": feature_branch,
                "base": target_branch,
                "maintainer_can_modify": True,
                "draft": False,
            }
        )
        if pr_create_resp.status_code not in (200, 201):
            error_data = pr_create_resp.json() if pr_create_resp.headers.get("content-type", "").startswith("application/json") else {}
            err_msg = error_data.get("message") or pr_create_resp.text
            return {
                "status": "ERROR",
                "repo_name": repo_name,
                "error": f"Failed to open pull request: {err_msg}"
            }

        pr_data = pr_create_resp.json()
        pr_url = pr_data.get("html_url")
        pr_number = pr_data.get("number")

        logger.info(f"Successfully created GitHub Pull Request #{pr_number} on {repo_name}: {pr_url}")
        return {
            "status": "SUCCESS",
            "repo_name": repo_name,
            "branch_name": feature_branch,
            "target_branch": target_branch,
            "pr_url": pr_url,
            "pr_number": pr_number,
            "title": pr_title,
            "auto_merge_disabled": True,
        }
